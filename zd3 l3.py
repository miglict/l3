# -*- coding: cp1251 -*-

def main():
    print("Лабораторная работа №3. Задание 3. Вариант 5.")

    # Ввод данных
    try:
        xb = float(input('Введите Xbeg (начало интервала, |x|<1): '))
        xe = float(input('Введите Xend (конец интервала, |x|<1): '))
        dx = float(input('Введите Dx (шаг): '))
        eps = float(input('Введите Eps (точность): '))

        # Проверка области определения
        if abs(xb) >= 1 or abs(xe) >= 1:
            print("Ошибка: Аргумент x должен быть по модулю меньше 1 (|x| < 1)")
            return

        # Вывод заголовка
        print(f"\nXbeg={xb:7.2f}  Xend={xe:7.2f}")
        print(f"Dx={dx:7.2f}  Eps={eps:7.6f}\n")

        # Шапка таблицы
        print("+----------+----------+----------+")
        print("|    X     |    Y     |    N     |")
        print("+----------+----------+----------+")

        xt = xb

        # Внешний цикл по аргументу x
        while xt <= xe + 1e-9:
            # Инициализация для ряда
            # Первый член ряда (при n=0) для функции 2*(x + x^3/3...) равен 2*x
            an = 2 * xt
            y = an  # Сумма ряда
            n = 0  # Счетчик членов

            # Внутренний цикл вычисления суммы ряда
            while True:
                # Рекуррентная формула:
                # Следующий член = Предыдущий * x^2 * (2n+1)/(2n+3)
                k = (xt ** 2) * (2 * n + 1) / (2 * n + 3)

                an = an * k
                y = y + an
                n = n + 1

                # Проверка точности
                if abs(an) < eps:
                    break

            # Вывод строки таблицы
            print(f"|{xt:^10}|{y:^10}|{n:^10}|")

            xt += dx

        print("+----------+----------+----------+")

    except ValueError:
        print("Ошибка: введены некорректные данные.")


if __name__ == "__main__":
    main()